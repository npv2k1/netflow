export function inferConnectionType(a: DeviceType, b: DeviceType): ConnectionType {
  if (a === 'internet' || b === 'internet') return 'fiber';
  if (
    (a === 'gateway' || b === 'gateway' || a === 'vpn' || b === 'vpn') &&
    (a === 'modem' || b === 'modem' || a === 'firewall' || b === 'firewall')
  ) {
    return 'fiber';
  }
  if (
    a === 'phone' ||
    b === 'phone' ||
    a === 'laptop' ||
    b === 'laptop'
  ) {
    if (a === 'router' || b === 'router' || a === 'ap' || b === 'ap') {
      return 'wifi';
    }
  }
  if (a === 'ap' || b === 'ap') {
    if (a === 'camera' || b === 'camera' || a === 'printer' || b === 'printer') {
      return 'wifi';
    }
  }
  return 'ethernet';
}

